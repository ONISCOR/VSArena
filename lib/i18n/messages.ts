export const messages = { en, it };

/**
 * Dictionary for a locale.
 */
export function dict(locale: Locale): Messages {
  return messages[locale];
}

/**
 * Nav or footer label for a chrome link key.
 */
export function chromeLink(m: Messages, key: string): string {
  const nav = m.nav as Record<string, string>;
  if (nav[key]) return nav[key];
  const foot = m.footer as Record<string, string>;
  return foot[key] ?? key;
}

/**
 * Replace `{name}` / `{n}` placeholders.
 */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? ""));
}
